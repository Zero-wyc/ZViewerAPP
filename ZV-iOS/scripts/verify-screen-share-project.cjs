const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const plist = require('@expo/plist').default;
const xcode = require('xcode');
const root = path.resolve(__dirname, '..');
const project = xcode.project(path.join(root, 'ios/ZViewer.xcodeproj/project.pbxproj'));
project.parseSync();
const objects = project.hash.project.objects;
const targets = Object.entries(project.pbxNativeTargetSection()).filter(([, value]) => typeof value === 'object');
const broadcasts = targets.filter(([, value]) => value.name.replaceAll('"', '') === 'ZViewerBroadcast');
assert.equal(broadcasts.length, 1, 'Expected exactly one broadcast target');
const [broadcast, target] = broadcasts[0];
const host = project.getFirstTarget();
assert.ok(host.firstTarget.dependencies.some(item => objects.PBXTargetDependency[item.value]?.target === broadcast), 'Missing host dependency');
const sources = target.buildPhases.map(item => objects.PBXSourcesBuildPhase[item.value]).filter(Boolean);
assert.equal(sources.length, 1);
assert.equal(sources[0].files.length, 1, 'Unexpected extension source files');
const copyPhases = host.firstTarget.buildPhases.map(item => objects.PBXCopyFilesBuildPhase?.[item.value]).filter(Boolean);
assert.equal(copyPhases.flatMap(item => item.files).filter(item => objects.PBXBuildFile[item.value]?.fileRef === target.productReference).length, 1, 'Missing or duplicate embedded extension');
const readPlist = file => plist.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const app = readPlist('ios/ZViewer/Info.plist');
const extension = readPlist('ios/ZViewerBroadcast/ZViewerBroadcast-Info.plist');
const hostEntitlements = readPlist('ios/ZViewer/ZViewer.entitlements');
const extensionEntitlements = readPlist('ios/ZViewerBroadcast/ZViewerBroadcast.entitlements');
assert.equal(app.ZViewerShareKeychainGroup, extension.ZViewerShareKeychainGroup);
assert.deepEqual(hostEntitlements['com.apple.security.application-groups'], extensionEntitlements['com.apple.security.application-groups']);
assert.ok(hostEntitlements['keychain-access-groups'].includes(extensionEntitlements['keychain-access-groups'][0]));
assert.equal(extension.NSExtension.NSExtensionPointIdentifier, 'com.apple.broadcast-services-upload');
assert.ok(app.UIBackgroundModes.includes('screen-capture'));
const podfile = fs.readFileSync(path.join(root, 'ios/Podfile'), 'utf8');
const extensionPods = podfile.split("target 'ZViewerBroadcast' do")[1];
assert.ok(extensionPods?.includes("pod 'ZViewerScreenShare'"));
assert.ok(!extensionPods.includes('use_expo_modules!'));
console.log('Broadcast project verified: one target, embedded dependency, shared entitlements, isolated native transport');
